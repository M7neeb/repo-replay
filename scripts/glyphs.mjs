// Renders the few font sizes the share image uses into server/glyphs.ts, so the server can set text
// without a font engine. Run with `node scripts/glyphs.mjs` after changing FONTS.
import { chromium } from '@playwright/test';
import { readFileSync, writeFileSync } from 'node:fs';
import { deflateRawSync } from 'node:zlib';

const FONTS = {
  b42: { weight: 700, size: 42 },
  r26: { weight: 400, size: 26 },
  s24: { weight: 600, size: 24 },
  r24: { weight: 400, size: 24 },
  r22: { weight: 400, size: 22 },
};
// glyphs are drawn at three sub-pixel offsets so text keeps even spacing
const PHASES = 3;
const FIRST = 32;
const LAST = 126;

const dir = new URL('../node_modules/@fontsource/noto-sans/files/', import.meta.url);
const faces = Object.fromEntries(
  [...new Set(Object.values(FONTS).map((f) => f.weight))].map((w) => [w, readFileSync(new URL(`noto-sans-latin-${w}-normal.woff2`, dir)).toString('base64')]),
);

const browser = await chromium.launch();
const page = await browser.newPage();
const out = await page.evaluate(
  async ({ FONTS, faces, PHASES, FIRST, LAST }) => {
    for (const [w, b64] of Object.entries(faces)) {
      const bytes = Uint8Array.from(atob(b64), (c) => c.charCodeAt(0));
      const face = new FontFace('Noto', bytes, { weight: w });
      await face.load();
      document.fonts.add(face);
    }
    const result = {};
    for (const [key, f] of Object.entries(FONTS)) {
      const pad = Math.ceil(f.size * 0.4);
      const cw = Math.ceil(f.size * 1.6) + pad * 2;
      const ch = Math.ceil(f.size * 1.6) + pad * 2;
      const canvas = new OffscreenCanvas(cw, ch);
      const ctx = canvas.getContext('2d', { willReadFrequently: true });
      ctx.font = `${f.weight} ${f.size}px Noto`;
      const base = pad + Math.ceil(f.size * 1.1);
      const m = ctx.measureText('Hg');
      const glyphs = [];
      const bitmaps = [];
      const adv = {};
      for (let c = FIRST; c <= LAST; c++) adv[c] = ctx.measureText(String.fromCharCode(c)).width;
      for (let c = FIRST; c <= LAST; c++) {
        const phases = [];
        for (let p = 0; p < PHASES; p++) {
          ctx.clearRect(0, 0, cw, ch);
          ctx.fillStyle = '#000';
          ctx.fillText(String.fromCharCode(c), pad + p / PHASES, base);
          const data = ctx.getImageData(0, 0, cw, ch).data;
          let x0 = cw, y0 = ch, x1 = -1, y1 = -1;
          for (let y = 0; y < ch; y++) for (let x = 0; x < cw; x++) {
            if (data[(y * cw + x) * 4 + 3] > 0) {
              if (x < x0) x0 = x;
              if (x > x1) x1 = x;
              if (y < y0) y0 = y;
              if (y > y1) y1 = y;
            }
          }
          if (x1 < 0) {
            phases.push([0, 0, 0, 0]);
            continue;
          }
          const gw = x1 - x0 + 1, gh = y1 - y0 + 1;
          const bm = [];
          for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) bm.push(data[(y * cw + x) * 4 + 3]);
          bitmaps.push(bm);
          phases.push([x0 - pad, y0 - base, gw, gh]);
        }
        glyphs.push(phases);
      }
      const kern = {};
      for (let a = FIRST; a <= LAST; a++) for (let b = FIRST; b <= LAST; b++) {
        const k = ctx.measureText(String.fromCharCode(a, b)).width - adv[a] - adv[b];
        if (Math.abs(k) >= 0.1) kern[String.fromCharCode(a, b)] = Math.round(k * 100) / 100;
      }
      result[key] = { size: f.size, ascent: Math.round(m.fontBoundingBoxAscent), adv: Object.values(adv).map((v) => Math.round(v * 100) / 100), glyphs, bitmaps, kern };
    }
    return result;
  },
  { FONTS, faces, PHASES, FIRST, LAST },
);
await browser.close();

// one byte array for every bitmap; each glyph phase records [dx, dy, w, h, offset]
const all = [];
const fonts = {};
for (const [key, f] of Object.entries(out)) {
  let bi = 0;
  const glyphs = f.glyphs.map((phases) => phases.map(([dx, dy, w, h]) => {
    if (!w) return [0, 0, 0, 0, 0];
    const at = all.length;
    for (const v of f.bitmaps[bi++]) all.push(v);
    return [dx, dy, w, h, at];
  }));
  fonts[key] = { size: f.size, ascent: f.ascent, adv: f.adv, glyphs, kern: f.kern };
}
const packed = deflateRawSync(Uint8Array.from(all), { level: 9 }).toString('base64');

writeFileSync(
  new URL('../server/glyphs.ts', import.meta.url),
  `// Generated by scripts/glyphs.mjs from Noto Sans (SIL Open Font License 1.1). Do not edit.\n`
    + `export const FIRST = ${FIRST};\nexport const PHASES = ${PHASES};\n`
    + `export const FONTS = ${JSON.stringify(fonts)} as const;\n`
    + `export const BITMAPS = '${packed}';\n`,
);
console.log(`${all.length} bytes of glyphs, ${packed.length} as text`);
